#!/usr/bin/env node
/**
 * A phone-sized copy of every photograph the shop puts on a page.
 *
 * Run: node theme/make-photo-sizes.js
 *
 * **Why.** Measured on the home page at 390 with the network throttled to a
 * filter-breaker's line, the four product photographs are 655KB of a 2.5MB
 * page — and they are the part gzip cannot help, the same way the icon fonts
 * were. They hold 1400x990 each. The hero draws one into 267x242 CSS pixels on
 * that screen; a 2x phone can show 534 across. The other 866 are downloaded,
 * decoded, and thrown away.
 *
 * 1400 is not a mistake: `make-hero-photos.js` chose it so the hero still
 * holds up on a 2x *desktop*, where it draws 583 CSS pixels and wants 1166.
 * Both are true, which is what `srcset` is for — one photograph at two sizes,
 * and the browser takes the one its screen can use. Nobody loses the sharp
 * version and the phone stops paying for it: **655KB becomes 217KB.**
 *
 * **Resize only** — the same rule the category tiles and the app icon are
 * under. No crop, no re-framing, no cut-out: `sharp().resize(700)` and the
 * encoder settings `make-hero-photos.js` already argued for (q88, alpha 100),
 * so the small copy is the large one and nothing else.
 *
 * The manifest is what the site reads. `photo_srcset()` in PHP and the
 * `<img>` pass in `make-rtl-page.js` both look a path up in it and write the
 * same two candidates; a photograph that is not in it gets a plain `src` and
 * nothing breaks. `PhotoSizesTest` checks the files it names are on disk,
 * because a manifest naming a file that is not there is a 404 per photograph.
 */
const fs = require('fs');
const path = require('path');
const sharp = require('./node_modules/sharp');

const ROOT = path.resolve(__dirname, '..');
const IMG = path.join(ROOT, 'download-version/assets/img');
const MANIFEST = path.join(IMG, 'photo-sizes.json');

/**
 * The width the small copy is cut to.
 *
 * 700 is the phone's 534 with room over it, and it is also what a 1200-wide
 * desktop asks for at 1x (480). One extra file per photograph rather than
 * three: the two candidates already cover every screen this shop sees, and
 * each additional width is another file to keep in step with the original.
 */
const SMALL = 700;

/**
 * Where the photographs are.
 *
 * `hero/` is the product photography — the five shots the catalogue's media
 * rows point at, which is every product picture the site draws. The rest of
 * `img/` is furniture: brand marks, category tiles, icons and shapes, all
 * already at or near the size they are drawn at, and none of them worth a
 * second file.
 */
const DIRS = ['hero'];

/** Anything narrower than this is already phone-sized. */
const FLOOR = SMALL * 1.3;

/**
 * And anything lighter than this is not worth a second file.
 *
 * `hero/` also holds two of the template's background shapes — 1800 pixels
 * wide and 10KB, because they are three flat colours. A small copy of one
 * saves 9KB and costs a file that has to be kept in step with the original for
 * ever. The photographs it is meant to catch are 100KB and up.
 */
const WORTH_IT = 60 * 1024;

async function main() {
  const manifest = {};
  let was = 0;
  let now = 0;

  for (const dir of DIRS) {
    for (const name of fs.readdirSync(path.join(IMG, dir)).sort()) {
      // WebP in, WebP out. A `.png` name holding WebP bytes is a file whose
      // extension lies to the server about its type, and every photograph
      // here is already WebP for the reasons make-hero-photos.js sets out.
      if (!/\.webp$/i.test(name) || /-\d+\.webp$/i.test(name)) continue;

      const file = path.join(IMG, dir, name);
      const meta = await sharp(file).metadata();
      if (meta.width < FLOOR || fs.statSync(file).size < WORTH_IT) continue;

      const small = name.replace(/\.webp$/i, `-${SMALL}.webp`);
      const out = path.join(IMG, dir, small);

      // Always cut from the original, never from the last small copy.
      const buffer = await sharp(file)
        .resize(SMALL)
        .webp({ quality: 88, alphaQuality: 100, effort: 6 })
        .toBuffer();

      fs.writeFileSync(out, buffer);

      manifest[`assets/img/${dir}/${name}`] = {
        small: `assets/img/${dir}/${small}`,
        smallWidth: SMALL,
        width: meta.width,
      };

      was += fs.statSync(file).size;
      now += buffer.length;
      console.log(
        `  ${name.padEnd(34)} ${String(Math.round(fs.statSync(file).size / 1024)).padStart(4)}KB @${meta.width} ` +
        `-> ${String(Math.round(buffer.length / 1024)).padStart(3)}KB @${SMALL}`,
      );
    }
  }

  fs.writeFileSync(
    MANIFEST,
    JSON.stringify({ note: 'Generated by theme/make-photo-sizes.js. Do not edit.', photos: manifest }, null, 2) + '\n',
  );

  console.log(`\n${(was / 1024).toFixed(0)}KB of photograph is ${(now / 1024).toFixed(0)}KB at ${SMALL} wide.`);
  console.log('Run node theme/make-rtl-page.js, then node theme/sync-storefront-assets.js.');
}

main();
