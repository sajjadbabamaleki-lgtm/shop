/**
 * The two the client asked to be altered, and what the alteration is.
 *
 * Both are edits to somebody else's artwork, which is why they live here as
 * named, explained overrides rather than as a hand-edit to a generated file: a
 * re-run would silently undo a hand-edit, and nothing would say so.
 *
 * `path` replaces the whole `d`; `topCut` takes a fraction off the top of the
 * ink. Anything not named here ships exactly as it was drawn.
 */
const EDITS = {
  /**
   * ست ورزشی — «اون خط کج وسطش پاک بشه بجاش ۳۰ درصد از قسمت پایینش پر بشه».
   *
   * The vest is one compound path: an outer outline plus two inner subpaths
   * that are holes, and the sash is not drawn at all — it is the gap left
   * between those two holes. So removing it is not deleting a stroke, it is
   * merging the two holes into one, and the merged outline is the two traced
   * end to end with the sash's own two diagonals dropped:
   *
   *   hole A ended at (6, 26.672) and ran the diagonal up to (23.014, 7.735)
   *   hole B ran the other diagonal from (23.244, 12.192) down to (8.143, 29)
   *
   * The union keeps A's left wall down to the interior floor, B's floor and
   * right wall, and joins them at the corners the diagonals used to cut off:
   * `v15` carries the left wall from (6,14) to (6,29), `h20` crosses the floor.
   *
   * Then the fill. The vest's ink runs y 1..31, so three tenths of it is 9
   * units, and the interior's own walls are vertical below the shoulders — so
   * the fill is a plain rectangle across the interior from y 22 to the
   * interior floor at 29, which together with the 2 units of outer shell below
   * it makes the icon solid from y 22 to y 31. Nine of thirty.
   */
  'vp-cat-sport': {
    path:
      'M26.25 31H6a2 2 0 0 1-2-2V13.75A1.75 1.75 0 0 1 5.75 12H6a1 1 0 0 0 1-1V2.75A1.75 1.75 0 0 1 8.75 1h3.5A1.75 1.75 0 0 1 14 2.75V7a2 2 0 0 0 .09.593A4.7 4.7 0 0 0 16 8a4.7 4.7 0 0 0 1.91-.407A2 2 0 0 0 18 7V2.75A1.75 1.75 0 0 1 19.75 1h3.5A1.75 1.75 0 0 1 25 2.75l.025 8.477A1 1 0 0 0 26 12h.25A1.75 1.75 0 0 1 28 13.75v15.5A1.75 1.75 0 0 1 26.25 31'
      + 'M20 7a4 4 0 1 1-8 0V3H9v8a3 3 0 0 1-3 3v15h20V14a2.99 2.99 0 0 1-2.756-1.808L23.014 7.735L23 3h-3z'
      + 'M6 22h20v7H6z',
  },

  /**
   * بوت و نیم‌بوت — «از بالای قسمت بوت هم ۲۰ درصد حذف بشه», and then again:
   * «۲۰ درصد از بالای اون آیکون بوت و نیم بوتو ببری بنظرم خیلی بلنده».
   *
   * A crop, not a redraw: the shaft is a long straight wall, so moving the top
   * of the view box down that same wall shortens the boot and leaves every
   * curve in it untouched.
   *
   * **The two rounds compound, they do not add.** The second twenty per cent
   * was asked of the boot as it then stood, which was already four fifths of
   * the original — so it is 0.2 + 0.8 × 0.2 = 0.36 of the drawn ink, not 0.4.
   * Written as the arithmetic rather than as 0.36, because the next round of
   * this will be a third fifth and the sum has to stay readable.
   */
  'vp-cat-boot': { topCut: 0.2 + 0.8 * 0.2 },

  /**
   * «الان سایز مجلسی و کتونی ۵ درصد کوچیکتر بشن».
   *
   * These two are the tallest of the eight once every box is cropped to its
   * ink — a heel and a high-top both stand up, where the loafer, the sandal and
   * the cropped boot lie down — so they are the two that read as oversized in a
   * row fitted by the longer side. Five per cent of slack all round, which
   * shrinks the artwork without touching its shape.
   */
  'vp-cat-heel': { shrink: 0.05 },
  'vp-cat-sneaker': { shrink: 0.05 },
};

/**
 * Where a rendered icon's ink actually starts and stops, top and bottom, in its
 * own view-box units.
 *
 * Measured rather than read off the path, because a path's numbers are control
 * points and a curve leaves them behind — and because two of these eight are
 * altered above, so the drawn `d` is not the shipped one. Rasterising the
 * finished SVG is the only thing that answers for what a viewer sees.
 *
 * The same rule the rest of this repo works by, arriving inside a generator:
 * measure the thing that gets painted, never the box it sits in.
 */
async function inkBox(svg, viewBox) {
  const [vx, vy, vw, vh] = viewBox.split(/[\s,]+/).map(Number);
  const w = 512;
  const h = Math.max(1, Math.round((w * vh) / vw));

  const { data, info } = await sharp(Buffer.from(svg))
    .resize(w, h, { fit: 'fill' })
    .flatten({ background: '#FFFFFF' })
    .greyscale()
    .raw()
    .toBuffer({ resolveWithObject: true });

  let x0 = Infinity;
  let y0 = Infinity;
  let x1 = -1;
  let y1 = -1;

  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[y * info.width + x] < 230) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }

  if (x1 < 0) {
    throw new Error('An icon rendered blank — the fill colour or the body is wrong.');
  }

  return {
    left: vx + (x0 / info.width) * vw,
    right: vx + ((x1 + 1) / info.width) * vw,
    top: vy + (y0 / info.height) * vh,
    bottom: vy + ((y1 + 1) / info.height) * vh,
  };
}

