  'vp-cat-sneaker': ['phosphor', 'sneaker-move-fill'], // ونس و کتونی
  'vp-cat-college': ['fluent', 'mans-shoe'],          // کالج
  'vp-cat-sandal': ['fluent', 'womans-sandal'],       // صندل
