#!/usr/bin/env node
/*
 * The desktop shop, built from the phone's.
 *
 * «میخوام قسمت فروشگاه وبسایتو با زبان طراحی نسخه ی موبایل و همون آیتم ها و
 * کارایی باز طراحی کنی … اصلا نمیخوام نسخه موبایل حتی یک پیکسل تغییر … ایجاد
 * بشه». So the desktop is not redrawn by hand: every rule in tweaks.css that
 * styles a part of the listing inside a phone-only media query is copied,
 * scoped under `.vp-listing-panel` and re-issued at min-width 992, in source
 * order, followed by the desktop's own adjustments from
 * `theme/desktop-shop-extra.css`. The result replaces the block that starts
 * «⛔ The desktop shop speaks the phone's language.» in tweaks.css.
 *
 * Nothing below 992 is written, so the phone cannot move. Re-run this after
 * changing a phone rule for the listing, then sync-storefront-assets.js.
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const TWEAKS = path.join(__dirname, '../download-version/assets/css/tweaks.css');
const EXTRA = path.join(__dirname, 'desktop-shop-extra.css');

// The listing's parts. A selector naming none of them is left where it is.
const PARTS = [
  'vp-listing-panel', 'vp-shop-top', 'vp-shop-find', 'vp-shop-filter',
  'vp-shop-tabs', 'vp-shop-tab', 'vp-shop-sheet', 'vp-sheet', 'vp-price-',
  'vp-chip', 'vp-shop-strip', 'vp-shop-cat', 'vp-card', 'vp-stories',
  'vp-story', 'vp-shop-grid',
];

const START = "/* ⛔ The desktop shop speaks the phone's language.";
const MOTION_START = '/* The desktop shop\'s motion — generated by theme/make-desktop-shop.js.';
const MOTION_END = '/* end of the desktop shop\'s motion */\n\n';
// The stories' reduced-motion guard. Their animations live only in phone
// media, so the desktop's copies have to sit *before* this guard and carry a
// guard of their own at the same specificity, or someone who asked for less
// motion gets the full turn on a desktop. StoriesTest holds the order.
const GUARD = '@media (prefers-reduced-motion: reduce) {\n  .vp-story-ring.is-cut,';
const END = '@media (min-width: 1400px) {\n  .vp-listing-panel .vp-shop-grid > .col {\n    width: 20%;\n  }\n}\n\n';

// A media query that applies to a 390 phone and not to a desktop.
function phoneOnly(params) {
  if (/prefers-reduced-motion|hover|print/.test(params)) return false;
  const max = params.match(/max-width:\s*([\d.]+)px/);
  const min = params.match(/min-width:\s*([\d.]+)px/);
  if (!max || +max[1] < 390) return false;
  return !(min && +min[1] > 390);
}

let css = fs.readFileSync(TWEAKS, 'utf8');
if (css.includes(START)) {
  const a = css.indexOf(START);
  const b = css.indexOf(END, a) + END.length;
  css = css.slice(0, a) + css.slice(b);
}

if (css.includes(MOTION_START)) {
  const a = css.indexOf(MOTION_START);
  const b = css.indexOf(MOTION_END, a) + MOTION_END.length;
  css = css.slice(0, a) + css.slice(b);
}

const rules = [];
const motion = [];
postcss.parse(css).walkAtRules('media', (at) => {
  if (!phoneOnly(at.params)) return;
  at.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const scoped = rule.selectors
      .filter((s) => PARTS.some((p) => s.includes(p)))
      .map((s) => s.trim())
      .filter((s) => !s.startsWith(':root'))
      .map((s) => (s.includes('vp-listing-panel') ? s : `.vp-listing-panel ${s}`));
    if (!scoped.length) return;
    const decls = rule.nodes
      .filter((d) => d.type === 'decl')
      .map((d) => `\n  ${d.prop}: ${d.value}${d.important ? ' !important' : ''};`)
      .join('');
    const text = `${scoped.join(',\n')} {${decls}\n}`;
    (/\banimation\b/.test(decls) && !/animation:\s*none/.test(decls) ? motion : rules).push(text);
  });
});

const indent = (t) => t.split('\n').map((l) => (l.trim() ? `  ${l}` : l)).join('\n');
const extra = fs.readFileSync(EXTRA, 'utf8');

const block = `${START}

   «نسخه دستاپ فروشگاهش خیلی خیلی داغونه طراحیش و هیچ شباهتی به نسخه موبایل
   نداره … اصلا نمیخوام نسخه موبایل حتی یک پیکسل تغییر یا خرابی توش ایجاد
   بشه». Above 992 the listing was a different page — a framed panel, a
   heading, a radio-button sidebar and a sort select — while the phone had
   grown its own: the stories, the search pill and its filter popup, the tab
   row with the price and brand sheets, the category strip and the cards.

   **The first half of this block is generated** by theme/make-desktop-shop.js:
   every phone-only rule for those parts, scoped under .vp-listing-panel and
   re-issued at min-width 992 in source order. Nothing below 992 is written, so
   the phone cannot move. Change a phone rule, re-run the script. The second
   half is theme/desktop-shop-extra.css — the width, four and five columns, and
   the popups at a sheet's width. */
@media (min-width: 992px) {
${indent(rules.join('\n\n'))}
${indent(extra)}
}

${END}`;

const guardAt = css.indexOf(GUARD);
if (guardAt < 0) throw new Error('the stories reduced-motion guard has moved; update GUARD');
const motionBlock = `${MOTION_START}
   The listing's own story animations, at desktop widths, and their guard. See
   the block «⛔ The desktop shop speaks the phone's language.» */
@media (min-width: 992px) {
${indent(motion.join('\n\n'))}
}

@media (prefers-reduced-motion: reduce) {
  .vp-listing-panel .vp-story-ring.is-cut,
  .vp-listing-panel .vp-story-disc,
  .vp-listing-panel .vp-story-cut,
  .vp-listing-panel .vp-story-photo {
    animation: none;
  }

  .vp-listing-panel .vp-story-cut {
    opacity: 1;
  }

  .vp-listing-panel .vp-story-photo {
    display: none;
  }
}

${MOTION_END}`;
css = css.slice(0, guardAt) + motionBlock + css.slice(guardAt);

const sig = ':root {\n  --vp-design: ok;\n}';
const at = css.lastIndexOf(sig);
css = css.slice(0, at) + block + css.slice(at);
fs.writeFileSync(TWEAKS, css);
console.log(`${rules.length + motion.length} phone rules carried to the desktop (${motion.length} of them motion).`);
