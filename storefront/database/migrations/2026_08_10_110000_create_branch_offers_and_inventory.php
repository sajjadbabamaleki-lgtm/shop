        DB::statement('ALTER TABLE branch_offers ADD CONSTRAINT branch_offers_promotion_window_ordered CHECK (promotion_starts_at IS NULL OR promotion_ends_at IS NULL OR promotion_ends_at > promotion_starts_at)');

