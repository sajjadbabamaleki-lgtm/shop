            // Below this the branch's panel calls it low. Per branch because a
            // warehouse and a shop mean different things by "nearly out".
            $table->unsignedInteger('low_stock_threshold')->default(0);
            $table->timestamps();

            $table->unique(['branch_id', 'variant_id']);
            $table->index(['branch_id', 'sellable_stock']);
        });

        // The invariants that were on variants, now one level down. They are
        // constraints rather than checks in PHP for the reason they always
        // were: application-level checks lose the race under concurrency, and
        // overselling is the failure §16.2 refuses to accept.
        DB::statement('ALTER TABLE branch_inventory ADD CONSTRAINT branch_inventory_on_hand_not_negative CHECK (stock_on_hand >= 0)');
