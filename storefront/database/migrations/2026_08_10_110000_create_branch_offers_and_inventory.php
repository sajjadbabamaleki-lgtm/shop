/**
 * Price and stock stop belonging to a variant and start belonging to a branch.
 *
 * Until now a shoe had one price and one pile of stock, which was true while
 * there was one shop. §14 and §16 say otherwise: a franchise sets its own
 * price inside the policy central gives it, and holds its own stock. Shiraz
 * selling from Tehran's shelf is the failure this removes.
 *
 * Two tables rather than one, because they change for different reasons and at
 * different rates. A price is an editorial decision made occasionally by a
 * person and audited (§29). Stock moves on every sale, is written by the
 * checkout under a row lock, and is explained by its ledger. Putting them in
 * one row would mean every sale touches the priced row, and every price change
 * contends with the till.
 *
 * This migration only adds and copies. Nothing is dropped here — the columns it
 * copies from are removed by the migration immediately after, so that if the
 * backfill is wrong the data is still in its old place to compare against.
 */
return new class extends Migration
{
    public function up(): void
    {
        /*
         * What a branch sells a variant for.
         *
         * A variant with no row here is not sold by that branch. That is the
         * useful default: a franchise opens with an empty shop and lists what
         * it actually stocks, rather than inheriting the whole catalogue and
         * having to hide most of it.
         */
        Schema::create('branch_offers', function (Blueprint $table) {
            $table->id();
            $table->foreignId('branch_id')->constrained()->cascadeOnDelete();
            $table->foreignId('variant_id')->constrained()->cascadeOnDelete();

            // Integer Rial, as everywhere else. Money is never floated.
            $table->unsignedBigInteger('price');
            $table->unsignedBigInteger('compare_at_price')->nullable();

            // What this branch paid. Per branch, not per variant: two branches
            // buying the same shoe from different suppliers pay differently,
            // and a margin computed from somebody else's cost is fiction.
            $table->unsignedBigInteger('cost_price')->nullable();

            // Whether the branch is currently selling it. Distinct from
            // variants.status, which says whether the SKU exists at all: a
            // branch pausing a line must not delist it for everybody.
            $table->enum('status', ['active', 'inactive'])->default('active');

            $table->timestamp('promotion_starts_at')->nullable();
            $table->timestamp('promotion_ends_at')->nullable();
            $table->timestamps();

            // One offer per variant per branch. Two prices for one shoe in one
            // shop is not a state worth writing code to resolve.
            $table->unique(['branch_id', 'variant_id']);

            // The storefront's own query: this branch, everything sellable.
            $table->index(['branch_id', 'status']);
            $table->index('variant_id');
        });

        /*
         * What a branch physically has.
         *
         * The same shape the variant carried, with the same invariants, moved
         * down a level. sellable_stock stays generated by the database so no
         * application path can disagree with it (§31).
         */
        Schema::create('branch_inventory', function (Blueprint $table) {
            $table->id();
            $table->foreignId('branch_id')->constrained()->cascadeOnDelete();
            $table->foreignId('variant_id')->constrained()->cascadeOnDelete();

            $table->integer('stock_on_hand')->default(0);
            $table->integer('stock_reserved')->default(0);
